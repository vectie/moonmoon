import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const archivePath = process.env.E1_ASM_ARCHIVE ||
  path.join(homedir(), 'Downloads', 'e1_asm_251028.tar.gz')
const packageRoot = 'e1_asm_251028'
const urdfEntry = `${packageRoot}/urdf/e1_asm.urdf`
const generatedDir = fileURLToPath(new URL('./.generated/', import.meta.url))
const assetRoot = path.join(generatedDir, 'e1-asm-assets')
const targetPath = path.join(generatedDir, 'e1-asm-assembly.js')
const targetTrianglesPerMesh = Number(process.env.E1_ASM_TRIANGLES_PER_MESH || 240)
const reductionAlgorithm = 'viewport-voxel-area-silhouette-v1'

function writeUnavailable(status, detail) {
  mkdirSync(generatedDir, { recursive: true })
  writeFileSync(targetPath, `// Generated by ui/rabbita-moon/prepare-e1-asm-assets.mjs.
// Do not edit this file by hand.

export const E1_ASM_ASSEMBLY = ${JSON.stringify({
    ready: false,
    status,
    detail,
    source_archive: archivePath,
    root_link: 'base_link',
    link_count: 0,
    joint_count: 0,
    mesh_count: 0,
    links: [],
    joints: [],
    visuals: [],
  }, null, 2)}
`)
}

function runTar(args, options = {}) {
  const result = spawnSync('tar', args, {
    encoding: options.encoding ?? 'utf8',
    maxBuffer: 128 * 1024 * 1024,
  })
  if (result.error) throw result.error
  if (result.status !== 0) {
    throw new Error([
      `tar ${args.join(' ')} failed`,
      result.stdout,
      result.stderr,
    ].filter(Boolean).join('\n'))
  }
  return result.stdout
}

function attr(attrs, name, fallback = '') {
  const match = attrs.match(new RegExp(`${name}\\s*=\\s*"([^"]*)"`))
  return match ? match[1] : fallback
}

function parseVec(raw, fallback = [0, 0, 0]) {
  if (!raw) return fallback
  const values = raw.trim().split(/\s+/).map(Number)
  return values.length === 3 && values.every(Number.isFinite) ? values : fallback
}

function parseOrigin(block) {
  const match = block.match(/<origin\b([^>]*)\/>/)
  if (!match) return { xyz: [0, 0, 0], rpy: [0, 0, 0] }
  return {
    xyz: parseVec(attr(match[1], 'xyz')),
    rpy: parseVec(attr(match[1], 'rpy')),
  }
}

function parseLimit(block) {
  const match = block.match(/<limit\b([^>]*)\/>/)
  if (!match) return null
  return {
    lower: Number(attr(match[1], 'lower', '0')),
    upper: Number(attr(match[1], 'upper', '0')),
    effort: Number(attr(match[1], 'effort', '0')),
    velocity: Number(attr(match[1], 'velocity', '0')),
  }
}

function parseColor(block) {
  const match = block.match(/<color\b([^>]*)\/>/)
  if (!match) return [0.82, 0.84, 0.82, 1]
  return parseVec(attr(match[1], 'rgba'), [0.82, 0.84, 0.82, 1])
}

function meshName(filename) {
  return filename.split('/').pop()
}

function parseLinks(urdf) {
  const links = []
  for (const match of urdf.matchAll(/<link\b([^>]*)>([\s\S]*?)<\/link>/g)) {
    const name = attr(match[1], 'name')
    const block = match[2]
    const visualMatch = block.match(/<visual>([\s\S]*?)<\/visual>/)
    if (!visualMatch) {
      links.push({ name, visual: null })
      continue
    }
    const visual = visualMatch[1]
    const meshMatch = visual.match(/<mesh\b([^>]*)\/>/)
    const filename = meshMatch ? attr(meshMatch[1], 'filename') : ''
    links.push({
      name,
      visual: {
        origin: parseOrigin(visual),
        mesh_filename: filename,
        mesh_name: meshName(filename),
        color_rgba: parseColor(visual),
      },
    })
  }
  return links
}

function parseJoints(urdf) {
  const joints = []
  for (const match of urdf.matchAll(/<joint\b([^>]*)>([\s\S]*?)<\/joint>/g)) {
    const block = match[2]
    const parent = block.match(/<parent\b([^>]*)\/>/)
    const child = block.match(/<child\b([^>]*)\/>/)
    const axis = block.match(/<axis\b([^>]*)\/>/)
    joints.push({
      name: attr(match[1], 'name'),
      type: attr(match[1], 'type'),
      origin: parseOrigin(block),
      parent: parent ? attr(parent[1], 'link') : '',
      child: child ? attr(child[1], 'link') : '',
      axis: axis ? parseVec(attr(axis[1], 'xyz')) : [0, 0, 0],
      limit: parseLimit(block),
    })
  }
  return joints
}

function validateAssembly(links, joints) {
  const visuals = links.filter(link => link.visual?.mesh_name?.endsWith('.STL'))
  const meshNames = new Set(visuals.map(link => link.visual.mesh_name))
  if (links.length !== 25) {
    throw new Error(`E1 assembly should expose 25 links, got ${links.length}`)
  }
  if (joints.length !== 24) {
    throw new Error(`E1 assembly should expose 24 joints, got ${joints.length}`)
  }
  if (meshNames.size !== 25) {
    throw new Error(`E1 assembly should expose 25 unique visual STL meshes, got ${meshNames.size}`)
  }
  if (!meshNames.has('base_link.STL')) {
    throw new Error('E1 assembly did not expose base_link.STL')
  }
}

function compactPoint(view, offset) {
  return [
    Number(view.getFloat32(offset, true).toFixed(5)),
    Number(view.getFloat32(offset + 4, true).toFixed(5)),
    Number(view.getFloat32(offset + 8, true).toFixed(5)),
  ]
}

function triangleCentroid(points) {
  return [
    (points[0][0] + points[1][0] + points[2][0]) / 3,
    (points[0][1] + points[1][1] + points[2][1]) / 3,
    (points[0][2] + points[1][2] + points[2][2]) / 3,
  ]
}

function triangleArea(points) {
  const ax = points[1][0] - points[0][0]
  const ay = points[1][1] - points[0][1]
  const az = points[1][2] - points[0][2]
  const bx = points[2][0] - points[0][0]
  const by = points[2][1] - points[0][1]
  const bz = points[2][2] - points[0][2]
  const cx = ay * bz - az * by
  const cy = az * bx - ax * bz
  const cz = ax * by - ay * bx
  return Math.hypot(cx, cy, cz) * 0.5
}

function emptyBounds() {
  return {
    min: [Number.POSITIVE_INFINITY, Number.POSITIVE_INFINITY, Number.POSITIVE_INFINITY],
    max: [Number.NEGATIVE_INFINITY, Number.NEGATIVE_INFINITY, Number.NEGATIVE_INFINITY],
  }
}

function addPointToBounds(bounds, point) {
  for (let axis = 0; axis < 3; axis += 1) {
    bounds.min[axis] = Math.min(bounds.min[axis], point[axis])
    bounds.max[axis] = Math.max(bounds.max[axis], point[axis])
  }
}

function triangleBounds(triangles) {
  const bounds = emptyBounds()
  for (const triangle of triangles) {
    for (const point of triangle.points) {
      addPointToBounds(bounds, point)
    }
  }
  return {
    min: bounds.min.map(value => Number(value.toFixed(5))),
    max: bounds.max.map(value => Number(value.toFixed(5))),
  }
}

function chooseVoxelBins(bounds, targetTriangles) {
  const span = bounds.max.map((max, axis) => Math.max(0.000001, max - bounds.min[axis]))
  const volume = span[0] * span[1] * span[2]
  const cell = Math.cbrt(volume / Math.max(1, targetTriangles * 0.86))
  return span.map(axisSpan => Math.max(1, Math.ceil(axisSpan / cell)))
}

function voxelKey(centroid, bounds, bins) {
  return centroid.map((value, axis) => {
    const span = Math.max(0.000001, bounds.max[axis] - bounds.min[axis])
    const bucket = Math.floor(((value - bounds.min[axis]) / span) * bins[axis])
    return Math.max(0, Math.min(bins[axis] - 1, bucket))
  }).join(':')
}

function selectSilhouetteTriangles(triangles) {
  const selected = new Map()
  for (let axis = 0; axis < 3; axis += 1) {
    let min = null
    let max = null
    for (const triangle of triangles) {
      const value = triangle.centroid[axis]
      if (!min || value < min.centroid[axis] ||
        (value === min.centroid[axis] && triangle.area > min.area)) {
        min = triangle
      }
      if (!max || value > max.centroid[axis] ||
        (value === max.centroid[axis] && triangle.area > max.area)) {
        max = triangle
      }
    }
    if (min) selected.set(min.index, min)
    if (max) selected.set(max.index, max)
  }
  return selected
}

function reduceTrianglesForViewport(triangles, targetTriangles) {
  if (triangles.length <= targetTriangles) {
    return {
      triangles,
      bounds: triangleBounds(triangles),
      reduced_bounds: triangleBounds(triangles),
      voxel_bins: [1, 1, 1],
    }
  }

  const bounds = triangleBounds(triangles)
  const bins = chooseVoxelBins(bounds, targetTriangles)
  const selected = selectSilhouetteTriangles(triangles)
  const buckets = new Map()
  for (const triangle of triangles) {
    const key = voxelKey(triangle.centroid, bounds, bins)
    const current = buckets.get(key)
    if (!current || triangle.area > current.area) {
      buckets.set(key, triangle)
    }
  }
  for (const triangle of buckets.values()) {
    selected.set(triangle.index, triangle)
  }

  const maxCount = targetTriangles + 6
  if (selected.size > maxCount) {
    const keep = selectSilhouetteTriangles([...selected.values()])
    const ranked = [...selected.values()].sort((a, b) => b.area - a.area)
    for (const triangle of ranked) {
      if (keep.size >= maxCount) break
      keep.set(triangle.index, triangle)
    }
    selected.clear()
    for (const [index, triangle] of keep) {
      selected.set(index, triangle)
    }
  }

  if (selected.size < targetTriangles) {
    const ranked = [...triangles].sort((a, b) => b.area - a.area)
    for (const triangle of ranked) {
      if (selected.size >= targetTriangles) break
      selected.set(triangle.index, triangle)
    }
  }

  const reduced = [...selected.values()].sort((a, b) => a.index - b.index)
  return {
    triangles: reduced,
    bounds,
    reduced_bounds: triangleBounds(reduced),
    voxel_bins: bins,
  }
}

function parseBinaryStlReduced(filePath, maxTriangles) {
  const buffer = readFileSync(filePath)
  if (buffer.byteLength < 84) {
    throw new Error(`STL file is too small: ${filePath}`)
  }
  const view = new DataView(buffer.buffer, buffer.byteOffset, buffer.byteLength)
  const sourceTriangleCount = view.getUint32(80, true)
  const expectedBytes = 84 + sourceTriangleCount * 50
  if (expectedBytes > buffer.byteLength) {
    throw new Error(`STL file is truncated: ${filePath}`)
  }
  const sourceTriangles = []
  for (let tri = 0; tri < sourceTriangleCount; tri += 1) {
    const base = 84 + tri * 50
    const points = []
    for (let point = 0; point < 3; point += 1) {
      const offset = base + 12 + point * 12
      points.push(compactPoint(view, offset))
    }
    const area = triangleArea(points)
    if (area > 0 && points.every(point => point.every(Number.isFinite))) {
      sourceTriangles.push({
        index: tri,
        points,
        area,
        centroid: triangleCentroid(points),
      })
    }
  }
  const reduced = reduceTrianglesForViewport(sourceTriangles, maxTriangles)
  const triangles = reduced.triangles.map(triangle => triangle.points)
  return {
    source_triangle_count: sourceTriangleCount,
    triangle_count: triangles.length,
    reduction_algorithm: reductionAlgorithm,
    reduction_target_triangles: maxTriangles,
    reduction_voxel_bins: reduced.voxel_bins,
    source_bounds_m: reduced.bounds,
    reduced_bounds_m: reduced.reduced_bounds,
    sampled_triangles: triangles,
  }
}

if (!existsSync(archivePath)) {
  writeUnavailable('e1-asm-archive-missing', `Set E1_ASM_ARCHIVE or place archive at ${archivePath}`)
  console.log(`wrote unavailable E1 assembly bridge: ${targetPath}`)
  process.exit(0)
}

const urdf = runTar(['-xOf', archivePath, urdfEntry])
const links = parseLinks(urdf)
const joints = parseJoints(urdf)
validateAssembly(links, joints)
const requiredMeshPaths = links
  .filter(link => link.visual?.mesh_name?.endsWith('.STL'))
  .map(link => path.join(assetRoot, packageRoot, 'meshes', link.visual.mesh_name))

mkdirSync(assetRoot, { recursive: true })
if (!requiredMeshPaths.every(meshPath => existsSync(meshPath))) {
  rmSync(path.join(assetRoot, packageRoot), { recursive: true, force: true })
  runTar(['-xzf', archivePath, '-C', assetRoot, `${packageRoot}/meshes`, urdfEntry])
}

const visuals = links
  .filter(link => link.visual?.mesh_name?.endsWith('.STL'))
  .map(link => {
    const meshPath = path.join(assetRoot, packageRoot, 'meshes', link.visual.mesh_name)
    const meshSample = existsSync(meshPath)
      ? parseBinaryStlReduced(meshPath, targetTrianglesPerMesh)
      : {
        source_triangle_count: 0,
        triangle_count: 0,
        reduction_algorithm: reductionAlgorithm,
        reduction_target_triangles: targetTrianglesPerMesh,
        reduction_voxel_bins: [0, 0, 0],
        source_bounds_m: { min: [0, 0, 0], max: [0, 0, 0] },
        reduced_bounds_m: { min: [0, 0, 0], max: [0, 0, 0] },
        sampled_triangles: [],
      }
    return {
      link_id: link.name,
      geometry: 'mesh',
      format: 'stl',
      source: `e1_asm_251028:${link.visual.mesh_filename}`,
      mesh_name: link.visual.mesh_name,
      mesh_path: meshPath,
      asset_url: `/@fs${meshPath}`,
      origin: link.visual.origin,
      color_rgba: link.visual.color_rgba,
      ...meshSample,
      status: existsSync(meshPath) ? 'e1-asm-stl-ready' : 'e1-asm-stl-missing',
    }
  })

const assembly = {
  ready: true,
  status: 'e1-asm-25-stl-assembly-ready',
  source_archive: archivePath,
  source_urdf_entry: urdfEntry,
  root_link: 'base_link',
  link_count: links.length,
  joint_count: joints.length,
  mesh_count: visuals.length,
  target_triangles_per_mesh: targetTrianglesPerMesh,
  reduction_algorithm: reductionAlgorithm,
  links,
  joints,
  visuals,
}

mkdirSync(generatedDir, { recursive: true })
writeFileSync(targetPath, `// Generated by ui/rabbita-moon/prepare-e1-asm-assets.mjs.
// Do not edit this file by hand.
// Generated from ${archivePath}.

export const E1_ASM_ASSEMBLY = ${JSON.stringify(assembly, null, 2)}
`)

console.log(`wrote ${targetPath} with ${visuals.length} E1 assembly STL visuals`)

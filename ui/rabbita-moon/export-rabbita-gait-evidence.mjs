import { spawnSync } from 'node:child_process'
import { readFileSync, unlinkSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

await import(new URL('./scene3d.js', import.meta.url).href)
await globalThis.__moonmoonLoadAdapterRuntime?.()

const diagnostics = globalThis.__moonmoonGaitDiagnostics
if (!diagnostics?.moonphysReviewTraceEvidence || !diagnostics?.moonphysHingeMotorReplayEvidence) {
  throw new Error('scene3d.js did not expose Rabbita gait evidence exporters')
}

const targetUrl = new URL('../../src/suite_adapter_preview/generated_rabbita_noetix_evidence.mbt', import.meta.url)
const targetPath = fileURLToPath(targetUrl)
const repoRoot = fileURLToPath(new URL('../..', import.meta.url))
const checkOnly = process.argv.includes('--check')
const sampleCount = 24

const motionTrace = diagnostics.moonphysReviewTraceEvidence(sampleCount)
const hingeTrace = diagnostics.moonphysHingeMotorReplayEvidence(sampleCount)
const motionHingeReview = diagnostics.moonphysMotionHingeReviewEvidence(sampleCount)

function mbString(value) {
  return JSON.stringify(value)
}

function mbBool(value) {
  return value ? 'true' : 'false'
}

function mbDouble(value) {
  if (!Number.isFinite(value)) {
    throw new Error(`Cannot emit non-finite MoonBit number: ${value}`)
  }
  const rounded = Number(value.toFixed(6))
  if (Object.is(rounded, -0)) {
    return '0.0'
  }
  if (Number.isInteger(rounded)) {
    return `${rounded}.0`
  }
  return String(rounded)
}

function mbVec3(value) {
  return `{ x: ${mbDouble(value.x)}, y: ${mbDouble(value.y)}, z: ${mbDouble(value.z)} }`
}

function indent(text, spaces = 2) {
  const prefix = ' '.repeat(spaces)
  return text.split('\n').map(line => line ? `${prefix}${line}` : line).join('\n')
}

function mbArray(items, render) {
  if (items.length === 0) {
    return '[]'
  }
  return `[\n${items.map(item => indent(render(item), 2)).join(',\n')},\n]`
}

function mbProbe(sample) {
  return `{
  probe_id: ${mbString(sample.probe_id)},
  position: ${mbVec3(sample.position)},
  surface_elevation_m: ${mbDouble(sample.surface_elevation_m)},
  surface_normal: ${mbVec3(sample.surface_normal)},
  clearance_m: ${mbDouble(sample.clearance_m)},
  in_contact: ${mbBool(sample.in_contact)},
  local_grade: ${mbDouble(sample.local_grade)},
  status: ${mbString(sample.status)},
}`
}

function mbFootprint(footprint) {
  return `{
  footprint_id: ${mbString(footprint.footprint_id)},
  center: ${mbVec3(footprint.center)},
  half_length_m: ${mbDouble(footprint.half_length_m)},
  half_width_m: ${mbDouble(footprint.half_width_m)},
  active: ${mbBool(footprint.active)},
}`
}

function mbPatch(patch) {
  return `{
  patch_id: ${mbString(patch.patch_id)},
  center: ${mbVec3(patch.center)},
  half_length_m: ${mbDouble(patch.half_length_m)},
  half_width_m: ${mbDouble(patch.half_width_m)},
  sample_count: ${patch.sample_count},
  contact_count: ${patch.contact_count},
  min_clearance_m: ${mbDouble(patch.min_clearance_m)},
  max_clearance_m: ${mbDouble(patch.max_clearance_m)},
  average_surface_elevation_m: ${mbDouble(patch.average_surface_elevation_m)},
  average_surface_normal: ${mbVec3(patch.average_surface_normal)},
  samples: ${mbArray(patch.samples, mbProbe)},
  status: ${mbString(patch.status)},
}`
}

function mbContact(contact) {
  return `{
  contact_id: ${mbString(contact.contact_id)},
  footprint: ${mbFootprint(contact.footprint)},
  patch: ${mbPatch(contact.patch)},
  applied_force_n: ${mbVec3(contact.applied_force_n)},
}`
}

function mbMotionFrame(frame) {
  return `{
  time_s: ${mbDouble(frame.time_s)},
  phase_label: ${mbString(frame.phase_label)},
  support_foot: ${mbString(frame.support_foot)},
  review_id: ${mbString(frame.review.review_id)},
  center_of_mass: ${mbVec3(frame.review.center_of_mass)},
  center_of_mass_velocity: ${mbVec3(frame.review.center_of_mass_velocity)},
  total_mass_kg: ${mbDouble(frame.review.total_mass_kg)},
  contacts: ${mbArray(frame.review.contacts, mbContact)},
}`
}

function mbHingeStep(step) {
  return `{
  joint_id: ${mbString(step.joint_id)},
  before_position_rad: ${mbDouble(step.before_position_rad)},
  target_position_rad: ${mbDouble(step.target_position_rad)},
  target_velocity_rad_s: ${mbDouble(step.target_velocity_rad_s)},
  min_position_rad: ${mbDouble(step.limit.min_position_rad)},
  max_position_rad: ${mbDouble(step.limit.max_position_rad)},
  max_velocity_rad_s: ${mbDouble(step.limit.max_velocity_rad_s)},
  max_torque_nm: ${mbDouble(step.limit.max_torque_nm)},
  stiffness_nm_per_rad: ${mbDouble(step.stiffness_nm_per_rad)},
  damping_nm_s_per_rad: ${mbDouble(step.damping_nm_s_per_rad)},
}`
}

function mbHingeFrame(frame) {
  return `{
  frame_index: ${frame.frame_index},
  time_s: ${mbDouble(frame.time_s)},
  dt_s: ${mbDouble(frame.dt_s)},
  steps: ${mbArray(frame.steps, mbHingeStep)},
}`
}

const content = `///| Generated by ui/rabbita-moon/export-rabbita-gait-evidence.mjs.
///| Do not edit this file by hand.
///| Generated from ui/rabbita-moon/scene3d.js#__moonmoonGaitDiagnostics.

///|
#warnings("-unused_value")
fn generated_rabbita_noetix_evidence_source() -> String {
  "ui/rabbita-moon/scene3d.js#__moonmoonGaitDiagnostics"
}

///|
fn generated_rabbita_noetix_motion_trace_id() -> String {
  ${mbString(motionTrace.trace_id)}
}

///|
fn generated_rabbita_noetix_hinge_trace_id() -> String {
  ${mbString(hingeTrace.trace_id)}
}

///|
fn generated_rabbita_noetix_combined_review_id() -> String {
  ${mbString(motionHingeReview.review_id)}
}

///|
fn generated_rabbita_noetix_motion_frames() -> Array[
  RabbitaNoetixGeneratedMotionFrame,
] {
  ${indent(mbArray(motionTrace.frames, mbMotionFrame), 2).trimStart()}
}

///|
fn generated_rabbita_noetix_hinge_frames() -> Array[
  RabbitaNoetixGeneratedHingeFrame,
] {
  ${indent(mbArray(hingeTrace.frames, mbHingeFrame), 2).trimStart()}
}
`

function moonFmt(path) {
  const result = spawnSync(process.env.MOON_BIN ?? 'moon', ['fmt', path], {
    cwd: repoRoot,
    encoding: 'utf8',
  })
  if (result.error) {
    throw result.error
  }
  if (result.status !== 0) {
    throw new Error([
      `moon fmt failed for ${path}`,
      result.stdout,
      result.stderr,
    ].filter(Boolean).join('\n'))
  }
}

function formattedMoonBit(content) {
  const tempPath = fileURLToPath(new URL('../../src/suite_adapter_preview/generated_rabbita_noetix_evidence_check.mbt', import.meta.url))
  writeFileSync(tempPath, content)
  try {
    moonFmt(tempPath)
    return readFileSync(tempPath, 'utf8')
  } finally {
    unlinkSync(tempPath)
  }
}

if (checkOnly) {
  const formatted = formattedMoonBit(content)
  const current = readFileSync(targetPath, 'utf8')
  if (current !== formatted) {
    throw new Error(`${targetPath} is stale; run npm run export:gait-evidence`)
  }
} else {
  writeFileSync(targetPath, content)
  moonFmt(targetPath)
  console.log(`wrote ${targetPath}`)
}
